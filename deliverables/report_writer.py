"""Generate markdown and PDF reports from consensus JSON."""

import json
import logging
import os
from datetime import date
from pathlib import Path

import io, sys
if sys.platform == "win32":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace") if hasattr(sys.stdout, "buffer") else sys.stdout
from rich.console import Console

logger = logging.getLogger(__name__)
console = Console(file=sys.stdout)


def write_report(
    consensus: dict,
    case_name: str,
    round1_results: list,
    output_dir: Path = Path("output"),
    red_team: dict = None,
    pushback: dict = None,
    quant_analysis: dict = None,
    directions: list = None,
    case_tags: list = None,
) -> Path:
    """
    Generate a polished markdown report from consensus.
    Also attempts PDF conversion if weasyprint is available.
    Returns path to the markdown report.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    safe_name = case_name.lower().replace(" ", "_").replace("/", "_")
    md_path = output_dir / f"{safe_name}_report.md"

    md = _build_markdown(consensus, case_name, round1_results,
                         red_team=red_team, pushback=pushback,
                         quant_analysis=quant_analysis, directions=directions, case_tags=case_tags)
    md_path.write_text(md, encoding="utf-8")
    console.print(f"  ✓ {md_path}")

    # Try PDF conversion
    pdf_path = output_dir / f"{safe_name}_report.pdf"
    _try_pdf(md, pdf_path)

    return md_path


def _build_markdown(
    consensus: dict,
    case_name: str,
    round1_results: list,
    red_team: dict = None,
    pushback: dict = None,
    quant_analysis: dict = None,
    directions: list = None,
    case_tags: list = None,
) -> str:
    today = date.today().strftime("%B %d, %Y")
    num_agents = len(round1_results)
    sections = []

    tags_note = f" | Case tags: {', '.join(case_tags)}" if case_tags else ""
    dirs_note = f" | {len(directions)} competing strategies" if directions else ""
    sections.append(f"""# {case_name.replace('_', ' ').title()} — Consulting Analysis Report
*Generated by Consulting Swarm | {today} | {num_agents}-agent specialist panel, 3-round deliberation{dirs_note}{tags_note}*

---
""")

    # Executive Summary
    exec_summary = consensus.get("executive_summary", "_Not available._")
    sections.append(f"## Executive Summary\n\n{exec_summary}\n")

    # Bottom line callout
    bottom_line = consensus.get("bottom_line", "")
    if bottom_line:
        sections.append(f"> **Bottom Line:** {bottom_line}\n")

    # Problem Statement
    problem = consensus.get("problem_statement", "_Not available._")
    sections.append(f"## Problem Statement\n\n{problem}\n")

    # Methodology
    sections.append(f"""## Methodology

This analysis was conducted by a panel of {num_agents} AI consultant agents with diverse expertise spanning strategy, finance, operations, marketing, legal, and nonprofit management. The agents independently analyzed all case materials, then engaged in structured deliberation across 3 rounds to build consensus recommendations.

**Analysis Framework:** {consensus.get('analysis_framework', 'Multi-disciplinary consulting framework')}
""")

    # Key Findings
    findings = consensus.get("key_findings", [])
    if findings:
        sections.append("## Key Findings\n")
        for i, f in enumerate(findings, 1):
            if isinstance(f, dict):
                confidence_pct = int(f.get("confidence", 0.8) * 100)
                sections.append(f"### Finding {i}: {f.get('finding', '')}\n")
                sections.append(f"{f.get('evidence', '')}\n")
                sections.append(f"*Confidence: {confidence_pct}%*\n")
            else:
                sections.append(f"- {f}\n")

    # Recommendations
    recommendations = consensus.get("recommendations", [])
    if recommendations:
        sections.append("## Recommendations\n")
        for rec in recommendations:
            if not isinstance(rec, dict):
                continue
            rank = rec.get("rank", "")
            title = rec.get("title", "Recommendation")
            sections.append(f"### {rank}. {title}\n")
            sections.append(f"{rec.get('description', '')}\n")

            rationale = rec.get("rationale", "")
            if rationale:
                sections.append(f"**Why this matters:** {rationale}\n")

            steps = rec.get("implementation_steps", [])
            if steps:
                sections.append("**Implementation Steps:**")
                for step in steps:
                    sections.append(f"- {step}")
                sections.append("")

            meta_items = []
            if rec.get("timeline"):
                meta_items.append(f"**Timeline:** {rec['timeline']}")
            if rec.get("expected_impact"):
                meta_items.append(f"**Expected Impact:** {rec['expected_impact']}")
            if rec.get("panel_support"):
                meta_items.append(f"**Panel Support:** {rec['panel_support']}")
            if rec.get("cost_estimate"):
                meta_items.append(f"**Cost Estimate:** {rec['cost_estimate']}")
            if meta_items:
                sections.append(" | ".join(meta_items) + "\n")

            risks = rec.get("risks_and_mitigations", "")
            if risks:
                sections.append(f"**Risks & Mitigations:** {risks}\n")

    # Risk Assessment
    risk = consensus.get("risk_assessment", "")
    if risk:
        sections.append(f"## Risk Assessment\n\n{risk}\n")

    # Implementation Roadmap
    roadmap = consensus.get("implementation_roadmap", {})
    if roadmap:
        sections.append("## Implementation Roadmap\n")
        phase_labels = {
            "phase_1_0_3_months": "Phase 1: Months 0–3 (Quick Wins)",
            "phase_2_3_6_months": "Phase 2: Months 3–6 (Build)",
            "phase_3_6_12_months": "Phase 3: Months 6–12 (Scale)",
        }
        for key, label in phase_labels.items():
            items = roadmap.get(key, [])
            if items:
                sections.append(f"### {label}\n")
                for item in items:
                    sections.append(f"- {item}")
                sections.append("")

    # Dissenting Views
    minority = consensus.get("minority_views", [])
    if minority:
        sections.append("## Dissenting Views & Considerations\n")
        sections.append("_The following perspectives were raised by a minority of panels and warrant consideration despite not reaching consensus:_\n")
        for view in minority:
            if isinstance(view, dict):
                sections.append(f"**{view.get('view', '')}** *(raised by {view.get('raised_by', 'some panels')})*")
                merit = view.get("merit", "")
                if merit:
                    sections.append(f"_{merit}_")
                sections.append("")

    # Missing Information
    missing = consensus.get("missing_information", [])
    if missing:
        sections.append("## Further Investigation Recommended\n")
        for item in missing:
            sections.append(f"- {item}")
        sections.append("")

    # Quantitative Analysis
    if quant_analysis and quant_analysis.get("models"):
        sections.append("## Financial Analysis\n")
        sections.append("*Quantitative models derived from agent assumptions and validated with Python financial calculations.*\n")
        for model in quant_analysis["models"]:
            rec = model.get("recommendation", "")
            if not rec:
                continue
            sections.append(f"### {rec}")
            base = model.get("scenarios", {}).get("base", {})
            cons = model.get("scenarios", {}).get("conservative", {})
            opt = model.get("scenarios", {}).get("optimistic", {})
            if base:
                sections.append(f"| Scenario | Annual Revenue | Net Contribution |")
                sections.append(f"|----------|---------------|-----------------|")
                sections.append(f"| Conservative | ${cons.get('annual_revenue', 0):,.0f} | ${cons.get('net_contribution', 0):,.0f} |")
                sections.append(f"| Base Case | ${base.get('annual_revenue', 0):,.0f} | ${base.get('net_contribution', 0):,.0f} |")
                sections.append(f"| Optimistic | ${opt.get('annual_revenue', 0):,.0f} | ${opt.get('net_contribution', 0):,.0f} |")
                sections.append("")
            metrics = []
            if model.get("payback_months"):
                metrics.append(f"**Payback:** {model['payback_months']:.0f} months")
            if model.get("roi_percent") is not None:
                metrics.append(f"**ROI:** {model['roi_percent']:.0f}%")
            if model.get("npv_3yr"):
                metrics.append(f"**3-Year NPV:** ${model['npv_3yr']:,.0f}")
            if metrics:
                sections.append(" | ".join(metrics) + "\n")
            for flag in model.get("flags", []):
                sections.append(f"> ⚠️ **Flag:** {flag}\n")

    # Client Considerations (from pushback round)
    if pushback and not pushback.get("parse_error"):
        sections.append("## Client Considerations\n")
        sections.append("*The following objections were raised in a simulated client review and have been incorporated into the recommendations above.*\n")
        overall = pushback.get("overall_concern", "")
        if overall:
            sections.append(f"> **Primary concern:** {overall}\n")
        missing = pushback.get("missing", "")
        if missing:
            sections.append(f"> **Gap identified:** {missing}\n")
        for item in pushback.get("pushback", []):
            if not isinstance(item, dict):
                continue
            sections.append(f"### {item.get('recommendation', 'General')}")
            for obj in item.get("objections", []):
                sections.append(f"- *Objection:* {obj}")
            buy_in = item.get("conditions_for_buy_in", "")
            if buy_in:
                sections.append(f"- *Conditions for approval:* {buy_in}")
            sections.append("")

    # Red Team Analysis
    if red_team and not red_team.get("parse_error"):
        sections.append("## Red Team Analysis\n")
        sections.append("*Adversarial stress test: independent analysts attempted to find flaws in each recommendation.*\n")

        overall_risk = red_team.get("overall_risk_rating", "")
        critical_count = red_team.get("critical_count", 0)
        if overall_risk:
            risk_emoji = {"low": "🟢", "medium": "🟡", "high": "🔴"}.get(overall_risk, "⚪")
            sections.append(f"**Overall Risk Rating:** {risk_emoji} {overall_risk.upper()}")
        if critical_count:
            sections.append(f"\n> ⚠️ **{critical_count} critical vulnerabilit{'y' if critical_count == 1 else 'ies'} identified — review before proceeding.**\n")

        severity_order = ["critical", "high", "medium", "low"]
        vulns = sorted(red_team.get("vulnerabilities", []),
                       key=lambda v: severity_order.index(v.get("severity", "low")) if v.get("severity") in severity_order else 3)
        for v in vulns:
            if not isinstance(v, dict):
                continue
            sev = v.get("severity", "").upper()
            sev_badge = {"CRITICAL": "🔴", "HIGH": "🟠", "MEDIUM": "🟡", "LOW": "🟢"}.get(sev, "⚪")
            sections.append(f"**{sev_badge} {sev} — {v.get('recommendation', '')}**")
            sections.append(f"{v.get('vulnerability', '')}")
            mit = v.get("mitigation_suggestion", "")
            if mit:
                sections.append(f"*Mitigation: {mit}*")
            sections.append("")

        strongest = red_team.get("strongest_recommendation", "")
        weakest = red_team.get("weakest_recommendation", "")
        kill = red_team.get("kill_recommendation", "")
        if strongest:
            sections.append(f"**Most defensible recommendation:** {strongest}\n")
        if weakest:
            sections.append(f"**Most vulnerable recommendation:** {weakest}\n")
        if kill:
            sections.append(f"**If forced to cut one:** {kill}\n")

    # Appendix: Methodology
    sections.append(f"""## Appendix: Methodology Detail

**Agent Panel:** {num_agents} AI consultant agents across 10 expertise categories (strategy, finance, operations, marketing, HR, technology, legal, nonprofit, risk, creative)

**Round 1 — Individual Analysis:** All {num_agents} agents independently read the case brief and produced structured recommendations. Agents ran concurrently in batches of 10.

**Round 2 — Panel Deliberation:** Agents were grouped into panels of 5 with balanced expertise and seniority. Each panel deliberated to produce consensus recommendations, surfacing agreements and disagreements.

**Round 3 — Consensus Building:** A final synthesis pass reviewed all panel outputs to produce the definitive recommendations ranked by impact × feasibility.

**Model:** claude-sonnet-4-20250514 (Anthropic)
""")

    # Appendix: Stats
    if round1_results:
        all_recs = [r for a in round1_results for r in a.get("analysis", {}).get("recommendations", [])]
        sections.append(f"""## Appendix: Agent Deliberation Statistics

- **Total agents:** {num_agents}
- **Total recommendations generated (Round 1):** {len(all_recs)}
- **Unique recommendation titles:** {len(set(r.get('title','') for r in all_recs))}
- **Final recommendations:** {len(recommendations)}
""")

    return "\n".join(sections)


def _try_pdf(markdown_text: str, pdf_path: Path):
    """Attempt to convert markdown to PDF using available libraries."""
    # Try weasyprint + markdown
    try:
        import markdown as md_lib
        from weasyprint import HTML, CSS

        html_body = md_lib.markdown(markdown_text, extensions=["tables", "fenced_code"])
        html = f"""<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<style>
body {{ font-family: Arial, sans-serif; max-width: 800px; margin: 40px auto; line-height: 1.6; color: #333; }}
h1 {{ color: #1a1a2e; border-bottom: 3px solid #16213e; }}
h2 {{ color: #16213e; border-bottom: 1px solid #ccc; }}
h3 {{ color: #0f3460; }}
blockquote {{ border-left: 4px solid #0f3460; padding-left: 1em; color: #555; }}
table {{ border-collapse: collapse; width: 100%; }}
th, td {{ border: 1px solid #ddd; padding: 8px; text-align: left; }}
th {{ background-color: #16213e; color: white; }}
code {{ background: #f4f4f4; padding: 2px 4px; border-radius: 3px; }}
</style>
</head>
<body>{html_body}</body>
</html>"""
        HTML(string=html).write_pdf(str(pdf_path))
        console.print(f"  ✓ {pdf_path}")
    except ImportError:
        console.print(f"  [dim]↷ PDF skipped (weasyprint/markdown not available)[/dim]")
    except Exception as e:
        console.print(f"  [yellow]⚠ PDF generation failed: {e}[/yellow]")
